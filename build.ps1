param(
    [switch]$InstallDependencies,
    [switch]$NoZip,
    [switch]$SingleFile,
    [string]$DistDirectory = 'dist'
)

$ErrorActionPreference = 'Stop'
$projectRoot = $PSScriptRoot
$pythonExe = Join-Path $projectRoot '.venv\Scripts\python.exe'
$distRoot = [IO.Path]::GetFullPath($(if ([IO.Path]::IsPathRooted($DistDirectory)) { $DistDirectory } else { Join-Path $projectRoot $DistDirectory }))
$bundleDir = Join-Path $distRoot 'CameraDesk'
if (Test-Path -LiteralPath (Join-Path $bundleDir 'data')) {
    throw 'This output contains user data. Choose a fresh -DistDirectory; existing captures must be preserved.'
}
Push-Location -LiteralPath $projectRoot
try {
    if ($InstallDependencies) {
        if (-not (Test-Path -LiteralPath $pythonExe)) {
            & py -3.11 -m venv (Join-Path $projectRoot '.venv')
            if ($LASTEXITCODE -ne 0) { throw 'Could not create the Python 3.11 environment.' }
        }
        & $pythonExe -m pip install -r (Join-Path $projectRoot 'requirements-dev.txt')
        if ($LASTEXITCODE -ne 0) { throw 'Dependency installation failed.' }
    }
    if (-not (Test-Path -LiteralPath $pythonExe)) {
        throw 'Missing .venv. Run build.ps1 -InstallDependencies with 64-bit Python 3.11 installed.'
    }
    $layout = if ($SingleFile) { '--onefile' } else { '--onedir' }
    $packArgs = @('-m', 'PyInstaller', '--noconfirm', '--clean', $layout, '--windowed', '--noupx', '--name', 'CameraDesk')
    $packArgs += @('--distpath', $(if ($SingleFile) { $bundleDir } else { $distRoot }))
    if ($SingleFile) {
        foreach ($embedded in @('LICENSE', 'THIRD_PARTY.md', 'LICENSES')) {
            $target = if ($embedded -eq 'LICENSES') { 'LICENSES' } else { '.' }
            $packArgs += @('--add-data', ((Join-Path $projectRoot $embedded) + ';' + $target))
        }
        $pythonLicense = Join-Path (& $pythonExe -c 'import sys; print(sys.base_prefix)') 'LICENSE.txt'
        if (Test-Path -LiteralPath $pythonLicense) {
            $packArgs += @('--add-data', ($pythonLicense + ';LICENSES'))
        }
    }
    $iconPath = Join-Path $projectRoot 'assets\app.ico'
    if (Test-Path -LiteralPath $iconPath) {
        $packArgs += @('--icon', $iconPath)
    }
    $versionPath = Join-Path $projectRoot 'assets\version_info.txt'
    if (Test-Path -LiteralPath $versionPath) {
        $packArgs += @('--version-file', $versionPath)
    }
    $packArgs += (Join-Path $projectRoot 'main.py')
    & $pythonExe @packArgs
    if ($LASTEXITCODE -ne 0) { throw 'PyInstaller failed. The release was not created.' }

    # The application supplies Chinese labels itself; no Qt translations load.
    $translations = [IO.Path]::GetFullPath((Join-Path $bundleDir '_internal\PySide6\translations'))
    if ($translations.StartsWith([IO.Path]::GetFullPath($bundleDir) + [IO.Path]::DirectorySeparatorChar) -and (Test-Path -LiteralPath $translations)) {
        Remove-Item -LiteralPath $translations -Recurse -Force
    }
    foreach ($notice in @('README.md', 'LICENSE', 'THIRD_PARTY.md', 'LICENSES', 'assets')) {
        $noticePath = Join-Path $projectRoot $notice
        if (Test-Path -LiteralPath $noticePath) {
            Copy-Item -LiteralPath $noticePath -Destination $bundleDir -Recurse -Force
        }
    }
    $sourceDir = Join-Path $bundleDir 'source'
    New-Item -ItemType Directory -Path $sourceDir -Force | Out-Null
    foreach ($sourceItem in @('main.py', 'multicam', 'tests', 'assets', '.github', 'docs', 'scripts', 'requirements.txt', 'requirements-dev.txt', 'build.ps1', 'launch.cmd', '.gitignore', 'LICENSE', 'README.md', 'THIRD_PARTY.md', 'LICENSES', 'CHANGELOG.md', 'CONTRIBUTING.md')) {
        $sourcePath = Join-Path $projectRoot $sourceItem
        if (Test-Path -LiteralPath $sourcePath) {
            Copy-Item -LiteralPath $sourcePath -Destination $sourceDir -Recurse -Force
        }
    }
    # Remove generated bytecode from the copied source, confined to this build.
    $resolvedSource = [IO.Path]::GetFullPath($sourceDir)
    if (-not $resolvedSource.StartsWith([IO.Path]::GetFullPath($bundleDir) + [IO.Path]::DirectorySeparatorChar)) {
        throw 'Source cleanup target is outside the bundle.'
    }
    Get-ChildItem -LiteralPath $resolvedSource -Recurse -File -Filter '*.pyc' | Remove-Item -Force
    Get-ChildItem -LiteralPath $resolvedSource -Recurse -Directory -Filter '__pycache__' |
        Sort-Object { $_.FullName.Length } -Descending | Remove-Item -Force
    & $pythonExe (Join-Path $projectRoot 'scripts\runtime_info.py') $bundleDir
    if ($LASTEXITCODE -ne 0) { throw 'Could not write runtime information.' }
    if ($SingleFile) {
        $standalonePath = Join-Path $projectRoot 'CameraDesk-Standalone-Windows-x64.exe'
        Copy-Item -LiteralPath (Join-Path $bundleDir 'CameraDesk.exe') -Destination $standalonePath -Force
        Write-Host "Standalone executable: $standalonePath"
    }
    # No captures/settings are copied into a release.
    if (-not $NoZip) {
        $zipName = if ($SingleFile) { 'CameraDesk-Standalone-Windows-x64.zip' } else { 'CameraDesk-Windows-x64.zip' }
        $zipPath = Join-Path $projectRoot $zipName
        Compress-Archive -LiteralPath $bundleDir -DestinationPath $zipPath -Force
        Write-Host "Portable ZIP: $zipPath"
    }
    Write-Host "Executable: $(Join-Path $bundleDir 'CameraDesk.exe')"
}
finally {
    Pop-Location
}
